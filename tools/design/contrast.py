#!/usr/bin/env python3
"""Check WCAG 2.2 contrast for every text pairing in design/tokens.css, both themes.

Reads the hex primitives and the semantic tokens of each theme block, resolves var() chains,
and writes design/contrast.md. Exits non-zero if a pairing meant for body text falls below 4.5:1.

Usage:  python3 tools/design/contrast.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSS = (ROOT / "design" / "tokens.css").read_text()
MIN_RATIO = 4.5  # WCAG AA for body text
# (text token, background token). Keep in step with PAIRS in design/specimen.html.
PAIRS = [
    ("--text", "--bg"), ("--text", "--surface-1"), ("--text", "--surface-2"), ("--text", "--surface-3"),
    ("--text-strong", "--surface-2"), ("--text-muted", "--bg"), ("--text-muted", "--surface-1"),
    ("--text-muted", "--surface-2"), ("--accent-text", "--bg"), ("--accent-text", "--surface-1"),
    ("--accent-text", "--surface-2"), ("--on-accent", "--accent"), ("--text-inverse", "--surface-inverse"),
]


def block(selector_regex):
    m = re.search(selector_regex + r"\s*\{(.*?)\n\}", CSS, re.S)
    return dict(re.findall(r"(--[\w-]+):\s*([^;]+);", m.group(1)))


def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    hi, lo = sorted([lum(a), lum(b)], reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def main():
    prims = block(r":root")
    themes = {"carbon": block(r':root,\s*\[data-theme="carbon"\]'), "bone": block(r'\[data-theme="bone"\]')}
    lines = ["# Contrast report", "", "Generated by `tools/design/contrast.py` from `design/tokens.css`. Do not edit by hand.", ""]
    failed = 0
    for name, toks in themes.items():
        env = {**prims, **toks}

        def resolve(v):
            v = env[v].strip()
            while v.startswith("var("):
                v = env[v[4:-1]].strip()
            return v

        lines += [f"## {name} theme", "", f"Target {MIN_RATIO}:1 for every pairing.", "",
                  "| Text | Background | Ratio | Result |", "|---|---|---|---|"]
        for fg, bg in PAIRS:
            r = ratio(resolve(fg), resolve(bg))
            ok = r >= MIN_RATIO
            failed += not ok
            lines.append(f"| `{fg}` {resolve(fg)} | `{bg}` {resolve(bg)} | {r:.2f}:1 | {'pass' if ok else 'FAIL'} |")
        lines.append("")
    (ROOT / "design" / "contrast.md").write_text("\n".join(lines))
    print(f"{len(PAIRS) * len(themes)} pairings checked, {failed} below target")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
